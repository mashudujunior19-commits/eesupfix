-- Bulk order receivers: "Order Received" checklist.
--
--  * Several members can be bulk-order receivers (communities.eesupool_order
--    .receiver_roles). Each one sees what was ordered (get_role_checklist,
--    read-only) and, once the warehouse has DISPATCHED the order, an
--    "Order Received" checklist.
--  * On that checklist a receiver can only DECREASE a quantity (never above
--    what was ordered) and can flag an item as faulty with a comment and an
--    optional photo. Faulty items are sent to the warehouse admins.
--  * confirm_order_receipt() validates and saves the checklist. Afterwards the
--    expected delivery date and the order PIN are returned -- only to the
--    KasiPool admin and the bulk receivers.
--
-- "Dispatched" = the Operations app has recorded that the load left the Centre
-- (communities.pool_order_progress.departed_at).

CREATE TABLE IF NOT EXISTS "communities"."order_receipt_item" (
    "eesupool_order_id" integer NOT NULL REFERENCES "communities"."eesupool_order"("id") ON DELETE CASCADE,
    "product_id" integer NOT NULL,
    "user_id" "uuid" NOT NULL DEFAULT auth.uid(),
    "ordered_qty" integer NOT NULL,
    "received_qty" integer NOT NULL,
    "is_faulty" boolean NOT NULL DEFAULT false,
    "fault_comment" text,
    "fault_photo_url" text,
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY ("eesupool_order_id", "product_id", "user_id"),
    CONSTRAINT "order_receipt_item_qty_check" CHECK ("received_qty" >= 0 AND "received_qty" <= "ordered_qty")
);

CREATE TABLE IF NOT EXISTS "communities"."order_receipt" (
    "eesupool_order_id" integer NOT NULL REFERENCES "communities"."eesupool_order"("id") ON DELETE CASCADE,
    "user_id" "uuid" NOT NULL DEFAULT auth.uid(),
    "confirmed_at" timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY ("eesupool_order_id", "user_id")
);

-- What was reported to the warehouse.
CREATE TABLE IF NOT EXISTS "communities"."order_fault_report" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "eesupool_order_id" integer NOT NULL REFERENCES "communities"."eesupool_order"("id") ON DELETE CASCADE,
    "product_id" integer NOT NULL,
    "reported_by" "uuid" NOT NULL,
    "comment" text NOT NULL,
    "photo_url" text,
    "created_at" timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE "communities"."order_receipt_item" OWNER TO "postgres";
ALTER TABLE "communities"."order_receipt" OWNER TO "postgres";
ALTER TABLE "communities"."order_fault_report" OWNER TO "postgres";
ALTER TABLE "communities"."order_receipt_item" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "communities"."order_receipt" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "communities"."order_fault_report" ENABLE ROW LEVEL SECURITY;

