REVOKE ALL ON TABLE "communities"."order_fault_report" FROM PUBLIC, "anon", "authenticated";
GRANT ALL ON TABLE "communities"."order_receipt_item" TO "service_role";
GRANT ALL ON TABLE "communities"."order_receipt" TO "service_role";
GRANT ALL ON TABLE "communities"."order_fault_report" TO "service_role";


-- Helpers ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION "communities"."is_bulk_receiver"("_eesupool_order_id" integer) RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET search_path = public
    AS $$
    SELECT EXISTS (
        SELECT 1
        FROM communities.eesupool_order eo
        JOIN communities.eesupool_member m
            ON m.eesupool_id = eo.eesupool_id AND m.user_id = auth.uid()
        WHERE eo.id = _eesupool_order_id AND eo.receiver_roles ? m.id::text
    );
$$;

CREATE OR REPLACE FUNCTION "communities"."is_pool_admin_of_order"("_eesupool_order_id" integer) RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET search_path = public
    AS $$
    SELECT EXISTS (
        SELECT 1
        FROM communities.eesupool_order eo
        JOIN communities.eesupool_member m
            ON m.eesupool_id = eo.eesupool_id AND m.user_id = auth.uid()
        WHERE eo.id = _eesupool_order_id AND m.role = 'Admin'
    );
$$;

CREATE OR REPLACE FUNCTION "communities"."order_is_dispatched"("_eesupool_order_id" integer) RETURNS boolean
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET search_path = public
    AS $$
DECLARE
    _dispatched boolean := false;
BEGIN
    IF to_regclass('communities.pool_order_progress') IS NOT NULL THEN
        EXECUTE 'SELECT EXISTS (SELECT 1 FROM communities.pool_order_progress
                  WHERE eesupool_order_id = $1 AND departed_at IS NOT NULL)'
        INTO _dispatched USING _eesupool_order_id;
    END IF;
    RETURN COALESCE(_dispatched, false);
END;
$$;

REVOKE ALL ON FUNCTION "communities"."is_bulk_receiver"(integer) FROM PUBLIC, "anon";
REVOKE ALL ON FUNCTION "communities"."is_pool_admin_of_order"(integer) FROM PUBLIC, "anon";
REVOKE ALL ON FUNCTION "communities"."order_is_dispatched"(integer) FROM PUBLIC, "anon";
GRANT EXECUTE ON FUNCTION "communities"."is_bulk_receiver"(integer) TO "authenticated", "service_role";
GRANT EXECUTE ON FUNCTION "communities"."is_pool_admin_of_order"(integer) TO "authenticated", "service_role";
GRANT EXECUTE ON FUNCTION "communities"."order_is_dispatched"(integer) TO "authenticated", "service_role";


-- State of the receipt for the signed-in receiver ----------------------------------

CREATE OR REPLACE FUNCTION "communities"."get_order_receipt_state"("_eesupool_order_id" integer)
    RETURNS TABLE("is_receiver" boolean, "is_admin" boolean, "is_dispatched" boolean, "confirmed_at" timestamp with time zone)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET search_path = public
    AS $$
BEGIN
    RETURN QUERY SELECT
        communities.is_bulk_receiver(_eesupool_order_id),
        communities.is_pool_admin_of_order(_eesupool_order_id),
        communities.order_is_dispatched(_eesupool_order_id),
        (SELECT r.confirmed_at FROM communities.order_receipt r
          WHERE r.eesupool_order_id = _eesupool_order_id AND r.user_id = auth.uid());
END;
$$;


-- The "Order Received" checklist ---------------------------------------------------
-- No prices. Only a bulk receiver, and only once the warehouse has dispatched.

CREATE OR REPLACE FUNCTION "communities"."get_order_receipt"("_eesupool_order_id" integer)
    RETURNS TABLE("product_id" integer, "name" "text", "size" "text", "image_url" "text",
                  "ordered_qty" integer, "received_qty" integer, "is_faulty" boolean,
                  "fault_comment" "text", "fault_photo_url" "text")
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET search_path = public
    AS $$
BEGIN
    IF NOT communities.is_bulk_receiver(_eesupool_order_id) THEN
        RAISE EXCEPTION 'Only a bulk order receiver can confirm this order';
    END IF;
    IF NOT communities.order_is_dispatched(_eesupool_order_id) THEN
        RAISE EXCEPTION 'The warehouse has not dispatched this order yet';
    END IF;

    RETURN QUERY
    SELECT
        p.id,
        p.name,
        p.size,
        p.image_url,
        CAST(SUM(op.quantity) AS integer) AS ordered_qty,
        COALESCE(MAX(i.received_qty), CAST(SUM(op.quantity) AS integer)) AS received_qty,
        COALESCE(BOOL_OR(i.is_faulty), false),
        MAX(i.fault_comment),
        MAX(i.fault_photo_url)
    FROM sales.order_product op
    JOIN sales."order" o ON o.id = op.order_id
    JOIN inventory.product p ON p.id = op.product_id
    LEFT JOIN communities.order_receipt_item i
        ON i.eesupool_order_id = _eesupool_order_id
       AND i.product_id = p.id
       AND i.user_id = auth.uid()
    WHERE o.eesupool_order_id = _eesupool_order_id
      AND o.placed_at IS NOT NULL
      AND o.cancelled_at IS NULL
    GROUP BY p.id, p.name, p.size, p.image_url
    ORDER BY p.name;
END;
$$;


-- Save one line: quantity can only go DOWN from what was ordered. --------------------

CREATE OR REPLACE FUNCTION "communities"."save_order_receipt_item"(
    "_eesupool_order_id" integer, "_product_id" integer, "_received_qty" integer,
    "_is_faulty" boolean DEFAULT false, "_comment" text DEFAULT NULL, "_photo_url" text DEFAULT NULL
) RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET search_path = public
    AS $$
DECLARE
    _ordered integer;
BEGIN
    IF NOT communities.is_bulk_receiver(_eesupool_order_id) THEN
        RAISE EXCEPTION 'Only a bulk order receiver can confirm this order';
    END IF;
    IF NOT communities.order_is_dispatched(_eesupool_order_id) THEN
        RAISE EXCEPTION 'The warehouse has not dispatched this order yet';
    END IF;
    IF EXISTS (SELECT 1 FROM communities.order_receipt
               WHERE eesupool_order_id = _eesupool_order_id AND user_id = auth.uid()) THEN
        RAISE EXCEPTION 'You have already confirmed this order';
    END IF;

    SELECT CAST(SUM(op.quantity) AS integer) INTO _ordered
    FROM sales.order_product op
    JOIN sales."order" o ON o.id = op.order_id
    WHERE o.eesupool_order_id = _eesupool_order_id
      AND o.placed_at IS NOT NULL
      AND o.cancelled_at IS NULL
      AND op.product_id = _product_id;

    IF _ordered IS NULL THEN
        RAISE EXCEPTION 'That product is not on this order';
    END IF;
    IF _received_qty < 0 THEN
        RAISE EXCEPTION 'Quantity cannot be negative';
    END IF;
    IF _received_qty > _ordered THEN
        RAISE EXCEPTION 'You can only decrease a quantity, never increase it (ordered: %)', _ordered;
    END IF;
    IF _is_faulty AND COALESCE(trim(_comment), '') = '' THEN
        RAISE EXCEPTION 'Add a comment describing what is wrong with the item';
    END IF;

    INSERT INTO communities.order_receipt_item(
        eesupool_order_id, product_id, user_id, ordered_qty, received_qty,
        is_faulty, fault_comment, fault_photo_url, updated_at)
    VALUES (_eesupool_order_id, _product_id, auth.uid(), _ordered, _received_qty,
            COALESCE(_is_faulty, false),
            CASE WHEN _is_faulty THEN trim(_comment) END,
            CASE WHEN _is_faulty THEN _photo_url END,
            now())
    ON CONFLICT (eesupool_order_id, product_id, user_id) DO UPDATE SET
        ordered_qty = EXCLUDED.ordered_qty,
        received_qty = EXCLUDED.received_qty,
        is_faulty = EXCLUDED.is_faulty,
        fault_comment = EXCLUDED.fault_comment,
        fault_photo_url = EXCLUDED.fault_photo_url,
        updated_at = now();
END;
$$;


-- Confirm: validates every line, saves the checklist, reports faults. -----------------

CREATE OR REPLACE FUNCTION "communities"."confirm_order_receipt"("_eesupool_order_id" integer) RETURNS void
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET search_path = public
    AS $$
DECLARE
    _missing integer;
    _pool_name text;
    _fault record;
BEGIN
    IF NOT communities.is_bulk_receiver(_eesupool_order_id) THEN
        RAISE EXCEPTION 'Only a bulk order receiver can confirm this order';
    END IF;
    IF NOT communities.order_is_dispatched(_eesupool_order_id) THEN
        RAISE EXCEPTION 'The warehouse has not dispatched this order yet';
    END IF;
    IF EXISTS (SELECT 1 FROM communities.order_receipt
               WHERE eesupool_order_id = _eesupool_order_id AND user_id = auth.uid()) THEN
        RAISE EXCEPTION 'You have already confirmed this order';
    END IF;

    -- Every product on the order must have been checked (saved) by this receiver.
    SELECT COUNT(*) INTO _missing
    FROM (
        SELECT DISTINCT op.product_id
        FROM sales.order_product op
        JOIN sales."order" o ON o.id = op.order_id
        WHERE o.eesupool_order_id = _eesupool_order_id
          AND o.placed_at IS NOT NULL AND o.cancelled_at IS NULL
    ) ordered
    WHERE NOT EXISTS (
        SELECT 1 FROM communities.order_receipt_item i
        WHERE i.eesupool_order_id = _eesupool_order_id
          AND i.product_id = ordered.product_id
          AND i.user_id = auth.uid()
    );
    IF _missing > 0 THEN
        RAISE EXCEPTION 'Confirm every item first (% still unchecked)', _missing;
    END IF;

    INSERT INTO communities.order_receipt(eesupool_order_id, user_id) VALUES (_eesupool_order_id, auth.uid());

    SELECT ep.name INTO _pool_name
    FROM communities.eesupool_order eo JOIN communities.eesupool ep ON ep.id = eo.eesupool_id
    WHERE eo.id = _eesupool_order_id;

    -- Faulty items go to the warehouse admins.
    FOR _fault IN
        SELECT i.product_id, i.fault_comment, i.fault_photo_url, p.name
        FROM communities.order_receipt_item i
        JOIN inventory.product p ON p.id = i.product_id
        WHERE i.eesupool_order_id = _eesupool_order_id
          AND i.user_id = auth.uid() AND i.is_faulty
    LOOP
        INSERT INTO communities.order_fault_report(eesupool_order_id, product_id, reported_by, comment, photo_url)
        VALUES (_eesupool_order_id, _fault.product_id, auth.uid(), _fault.fault_comment, _fault.fault_photo_url);

        INSERT INTO engagements.notification(user_id, title, body, data, type, channel)
        SELECT a.user_id,
               'Faulty item reported',
               CONCAT(_pool_name, ' (order ', _eesupool_order_id, '): ', _fault.name, ' - ', _fault.fault_comment),
               jsonb_build_object('kind', 'fault_report', 'eesupool_order_id', _eesupool_order_id,
                                  'product_id', _fault.product_id, 'photo_url', _fault.fault_photo_url),
               'other', 'push'
        FROM public.profile a
        WHERE a.role = 'Admin';
    END LOOP;
END;
$$;


-- Expected delivery date + order PIN: KasiPool admin and bulk receivers only. ----------

CREATE OR REPLACE FUNCTION "communities"."get_order_delivery_info"("_eesupool_order_id" integer)
    RETURNS TABLE("expected_date" timestamp with time zone, "secret_pin" integer)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET search_path = public
    AS $$
BEGIN
    IF NOT (communities.is_pool_admin_of_order(_eesupool_order_id)
            OR communities.is_bulk_receiver(_eesupool_order_id)) THEN
        RAISE EXCEPTION 'Only the KasiPool admin and the bulk receivers can see this';
    END IF;

    RETURN QUERY
    SELECT eo.schedule_for, eo.secret_pin
    FROM communities.eesupool_order eo
    WHERE eo.id = _eesupool_order_id;
END;
$$;

