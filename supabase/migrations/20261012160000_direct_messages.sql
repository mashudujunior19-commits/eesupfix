-- Direct (one-to-one) messages.
--
-- * One conversation per pair of users (user_a < user_b keeps the pair unique).
-- * Messages are stored as plain text (unlike pool chats) so the server can run
--   the same keyword moderation as pool chats on every insert. Access is
--   limited to the two participants by RLS.
-- * A message that matches the moderation list is HELD: only its sender sees
--   it, no push is sent, and it waits in the app-admin review queue
--   (profile.role = 'Admin'). Recipients can report a delivered message, and
--   app admins can flag one by id; both put it back into the queue.
-- * Requires 20261012150000_chat_moderation.sql (moderation_check, is_app_admin).

-- 1. Tables ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS communities.dm_conversation (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_a uuid NOT NULL,
    user_b uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_message_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dm_conversation_ordered CHECK (user_a < user_b),
    CONSTRAINT dm_conversation_pair UNIQUE (user_a, user_b)
);
CREATE INDEX IF NOT EXISTS dm_conversation_user_b_idx ON communities.dm_conversation (user_b);

CREATE TABLE IF NOT EXISTS communities.dm_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id uuid NOT NULL REFERENCES communities.dm_conversation (id) ON DELETE CASCADE,
    sender_id uuid NOT NULL,
    content text NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz,
    is_approved boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    moderation_status text NOT NULL DEFAULT 'none'
        CHECK (moderation_status IN ('none', 'held', 'flagged', 'approved', 'rejected')),
    moderation_reason text,
    moderated_by uuid,
    moderated_at timestamptz
);
CREATE INDEX IF NOT EXISTS dm_message_conversation_idx ON communities.dm_message (conversation_id, created_at DESC);
CREATE INDEX IF NOT EXISTS dm_message_queue_idx ON communities.dm_message (created_at DESC)
    WHERE is_approved = false AND is_deleted = false;

-- 2. Row level security --------------------------------------------------------
ALTER TABLE communities.dm_conversation ENABLE ROW LEVEL SECURITY;
ALTER TABLE communities.dm_message ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS dm_conversation_select ON communities.dm_conversation;
CREATE POLICY dm_conversation_select ON communities.dm_conversation FOR SELECT TO authenticated
    USING (auth.uid() IN (user_a, user_b));

-- Participants see delivered messages; senders also see their own held/rejected ones.
DROP POLICY IF EXISTS dm_message_select ON communities.dm_message;
CREATE POLICY dm_message_select ON communities.dm_message FOR SELECT TO authenticated
    USING (
        EXISTS (SELECT 1 FROM communities.dm_conversation c
                WHERE c.id = conversation_id AND auth.uid() IN (c.user_a, c.user_b))
        AND ((is_approved AND NOT is_deleted) OR sender_id = auth.uid())
    );

DROP POLICY IF EXISTS dm_message_insert ON communities.dm_message;
CREATE POLICY dm_message_insert ON communities.dm_message FOR INSERT TO authenticated
    WITH CHECK (
        sender_id = auth.uid()
        AND EXISTS (SELECT 1 FROM communities.dm_conversation c
                    WHERE c.id = conversation_id AND auth.uid() IN (c.user_a, c.user_b))
    );

GRANT SELECT ON communities.dm_conversation TO authenticated;
GRANT SELECT, INSERT ON communities.dm_message TO authenticated;

-- 3. Moderation on insert + delivery side effects --------------------------------
CREATE OR REPLACE FUNCTION communities.dm_before_insert() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE hit text;
BEGIN
    -- Whatever the client sent, moderation state is decided here.
    NEW.is_approved := true;
    NEW.is_deleted := false;
    NEW.moderation_status := 'none';
    NEW.moderation_reason := NULL;
    NEW.read_at := NULL;

    hit := communities.moderation_check(NEW.content);
    IF hit IS NOT NULL THEN
        NEW.is_approved := false;
        NEW.moderation_status := 'held';
        NEW.moderation_reason := 'Automatic: matched blocked term "' || hit || '"';
    END IF;
    RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS dm_before_insert_trigger ON communities.dm_message;
CREATE TRIGGER dm_before_insert_trigger BEFORE INSERT ON communities.dm_message
    FOR EACH ROW EXECUTE FUNCTION communities.dm_before_insert();

-- When a message becomes delivered (inserted clean, or approved by a reviewer):
-- bump the conversation and push-notify the recipient.
CREATE OR REPLACE FUNCTION communities.dm_after_delivery() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE
    recipient uuid;
    sender_name text;
BEGIN
    IF NOT NEW.is_approved OR NEW.is_deleted THEN RETURN NEW; END IF;
    IF TG_OP = 'UPDATE' AND OLD.is_approved THEN RETURN NEW; END IF;

    UPDATE communities.dm_conversation SET last_message_at = NEW.created_at
     WHERE id = NEW.conversation_id;

    SELECT CASE WHEN c.user_a = NEW.sender_id THEN c.user_b ELSE c.user_a END INTO recipient
      FROM communities.dm_conversation c WHERE c.id = NEW.conversation_id;

    SELECT COALESCE(NULLIF(btrim(CONCAT(p.first_name, ' ', p.last_name)), ''), p.corp_name, 'New message')
      INTO sender_name FROM public.profile p WHERE p.user_id = NEW.sender_id;

    PERFORM engagements.send_one_signal_push_notification(
        sender_name, left(NEW.content, 120), 'DIRECT_MESSAGE', NULL,
        jsonb_build_object('conversation_id', NEW.conversation_id), ARRAY[recipient]);
    RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS dm_after_insert_trigger ON communities.dm_message;
CREATE TRIGGER dm_after_insert_trigger AFTER INSERT ON communities.dm_message
    FOR EACH ROW EXECUTE FUNCTION communities.dm_after_delivery();
DROP TRIGGER IF EXISTS dm_after_update_trigger ON communities.dm_message;
CREATE TRIGGER dm_after_update_trigger AFTER UPDATE OF is_approved ON communities.dm_message
    FOR EACH ROW EXECUTE FUNCTION communities.dm_after_delivery();

-- 4. RPCs ------------------------------------------------------------------------
-- Finds or creates the conversation with another user.
CREATE OR REPLACE FUNCTION communities.start_conversation(p_other_user uuid) RETURNS uuid
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE
    me uuid := auth.uid();
    a uuid;
    b uuid;
    conv uuid;
BEGIN
    IF me IS NULL THEN RAISE EXCEPTION 'Not signed in'; END IF;
    IF p_other_user IS NULL OR p_other_user = me THEN RAISE EXCEPTION 'Choose another user'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.profile WHERE user_id = p_other_user) THEN
        RAISE EXCEPTION 'User not found';
    END IF;

    a := LEAST(me, p_other_user);
    b := GREATEST(me, p_other_user);

    INSERT INTO communities.dm_conversation (user_a, user_b) VALUES (a, b)
    ON CONFLICT (user_a, user_b) DO NOTHING;

    SELECT id INTO conv FROM communities.dm_conversation WHERE user_a = a AND user_b = b;
    RETURN conv;
END; $$;

-- The caller's conversations, newest first. Only delivered messages (plus the
-- caller's own held ones) count towards the preview; unread counts delivered
-- messages from the other user.
CREATE OR REPLACE FUNCTION communities.get_conversations(p_limit integer DEFAULT 100)
RETURNS TABLE (
    conversation_id uuid, other_user_id uuid, other_name text,
    last_message text, last_message_at timestamptz, unread_count bigint
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = communities, public AS $$
    SELECT
        c.id,
        o.other_id,
        COALESCE(NULLIF(btrim(CONCAT(p.first_name, ' ', p.last_name)), ''), p.corp_name, 'Unknown') AS other_name,
        lm.content,
        COALESCE(lm.created_at, c.created_at),
        (SELECT count(*) FROM communities.dm_message m
          WHERE m.conversation_id = c.id AND m.sender_id <> auth.uid()
            AND m.is_approved AND NOT m.is_deleted AND m.read_at IS NULL)
    FROM communities.dm_conversation c
    CROSS JOIN LATERAL (SELECT CASE WHEN c.user_a = auth.uid() THEN c.user_b ELSE c.user_a END AS other_id) o
    LEFT JOIN public.profile p ON p.user_id = o.other_id
    LEFT JOIN LATERAL (
        SELECT m.content, m.created_at FROM communities.dm_message m
         WHERE m.conversation_id = c.id AND NOT m.is_deleted
           AND (m.is_approved OR m.sender_id = auth.uid())
         ORDER BY m.created_at DESC LIMIT 1
    ) lm ON true
    WHERE auth.uid() IN (c.user_a, c.user_b)
    ORDER BY COALESCE(lm.created_at, c.created_at) DESC
    LIMIT p_limit;
$$;

CREATE OR REPLACE FUNCTION communities.mark_conversation_read(p_conversation_id uuid) RETURNS void
    LANGUAGE sql SECURITY DEFINER SET search_path = communities, public AS $$
    UPDATE communities.dm_message m SET read_at = now()
     WHERE m.conversation_id = p_conversation_id AND m.sender_id <> auth.uid()
       AND m.read_at IS NULL AND m.is_approved
       AND EXISTS (SELECT 1 FROM communities.dm_conversation c
                    WHERE c.id = p_conversation_id AND auth.uid() IN (c.user_a, c.user_b));
$$;

-- People picker for "new conversation".
CREATE OR REPLACE FUNCTION communities.search_users_for_dm(p_query text, p_limit integer DEFAULT 20)
RETURNS TABLE (user_id uuid, full_name text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = communities, public AS $$
    SELECT p.user_id,
           COALESCE(NULLIF(btrim(CONCAT(p.first_name, ' ', p.last_name)), ''), p.corp_name, 'Unknown')
    FROM public.profile p
    WHERE char_length(btrim(p_query)) >= 3
      AND p.user_id <> auth.uid()
      AND (CONCAT(p.first_name, ' ', p.last_name) ILIKE '%' || btrim(p_query) || '%'
           OR p.corp_name ILIKE '%' || btrim(p_query) || '%')
    ORDER BY 2
    LIMIT p_limit;
$$;

-- A recipient reports a delivered message: it goes back to the review queue.
CREATE OR REPLACE FUNCTION communities.report_dm(p_message_id bigint, p_reason text DEFAULT NULL) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    UPDATE communities.dm_message m
       SET is_approved = false, moderation_status = 'flagged',
           moderation_reason = 'Reported by recipient' || COALESCE(': ' || NULLIF(btrim(p_reason), ''), ''),
           moderated_at = now()
     WHERE m.id = p_message_id AND m.sender_id <> auth.uid() AND m.is_approved AND NOT m.is_deleted
       AND EXISTS (SELECT 1 FROM communities.dm_conversation c
                    WHERE c.id = m.conversation_id AND auth.uid() IN (c.user_a, c.user_b));
    IF NOT FOUND THEN RAISE EXCEPTION 'Message not found'; END IF;
END; $$;

-- App-admin review queue ------------------------------------------------------------
CREATE OR REPLACE FUNCTION communities.get_held_dms(p_limit integer DEFAULT 100)
RETURNS TABLE (
    message_id bigint, conversation_id uuid, sender_id uuid, sender_name text,
    content text, moderation_status text, moderation_reason text, created_at timestamptz
)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    RETURN QUERY
    SELECT m.id, m.conversation_id, m.sender_id,
           COALESCE(NULLIF(btrim(CONCAT(p.first_name, ' ', p.last_name)), ''), p.corp_name, 'Unknown'),
           m.content, m.moderation_status, m.moderation_reason, m.created_at
      FROM communities.dm_message m
      LEFT JOIN public.profile p ON p.user_id = m.sender_id
     WHERE NOT m.is_approved AND NOT m.is_deleted
     ORDER BY m.created_at DESC
     LIMIT p_limit;
END; $$;

CREATE OR REPLACE FUNCTION communities.review_dm(p_message_id bigint, p_approve boolean) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    IF p_approve THEN
        UPDATE communities.dm_message
           SET is_approved = true, moderation_status = 'approved',
               moderated_by = auth.uid(), moderated_at = now()
         WHERE id = p_message_id;
    ELSE
        UPDATE communities.dm_message
           SET is_approved = false, is_deleted = true, moderation_status = 'rejected',
               moderated_by = auth.uid(), moderated_at = now()
         WHERE id = p_message_id;
    END IF;
END; $$;

-- Admin pulls any message (even one already delivered) into the queue.
CREATE OR REPLACE FUNCTION communities.flag_dm(p_message_id bigint, p_reason text DEFAULT NULL) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    UPDATE communities.dm_message
       SET is_approved = false, moderation_status = 'flagged',
           moderation_reason = COALESCE(NULLIF(btrim(p_reason), ''), 'Flagged by an admin'),
           moderated_by = auth.uid(), moderated_at = now()
     WHERE id = p_message_id AND NOT is_deleted;
END; $$;

GRANT EXECUTE ON FUNCTION
    communities.start_conversation(uuid), communities.get_conversations(integer),
    communities.mark_conversation_read(uuid), communities.search_users_for_dm(text, integer),
    communities.report_dm(bigint, text), communities.get_held_dms(integer),
    communities.review_dm(bigint, boolean), communities.flag_dm(bigint, text)
TO authenticated;

