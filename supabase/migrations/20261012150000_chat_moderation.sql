-- Chat moderation (keyword list).
--
-- Flow
--   * Messages are sent through communities.send_chat_message(). It checks the
--     plain text against communities.moderation_term. A match HOLDS the message:
--     is_approved = false, moderation_status = 'held'. Held messages are visible
--     only to their author and to reviewers, and trigger no push notification.
--   * Reviewers (the pool's Admins, or an app Admin: profile.role = 'Admin')
--     approve or reject via communities.review_message(), and can flag any
--     already-delivered message via communities.flag_message().
--   * Pools that already require approval for censored members keep working:
--     those messages are is_approved = false with moderation_status = 'none'.
--
-- NOTE: message content is encrypted client-side, so the server cannot read it
-- on its own. The app therefore sends the plain text alongside the encrypted
-- content for the check. A modified client could skip it, which is why the
-- check lives in one server function and not in the app.

-- 1. Columns ----------------------------------------------------------------
ALTER TABLE communities.message
    ADD COLUMN IF NOT EXISTS moderation_status text NOT NULL DEFAULT 'none',
    ADD COLUMN IF NOT EXISTS moderation_reason text,
    ADD COLUMN IF NOT EXISTS moderated_by uuid,
    ADD COLUMN IF NOT EXISTS moderated_at timestamptz;

ALTER TABLE communities.message DROP CONSTRAINT IF EXISTS message_moderation_status_check;
ALTER TABLE communities.message ADD CONSTRAINT message_moderation_status_check
    CHECK (moderation_status IN ('none', 'held', 'flagged', 'approved', 'rejected'));

CREATE INDEX IF NOT EXISTS message_moderation_queue_idx
    ON communities.message (eesupool_id, created_at DESC)
    WHERE is_approved = false AND is_deleted = false;

-- 2. Role helpers -----------------------------------------------------------
CREATE OR REPLACE FUNCTION communities.is_app_admin() RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
    AS $$
    SELECT EXISTS (SELECT 1 FROM public.profile p WHERE p.user_id = auth.uid() AND p.role = 'Admin');
$$;

CREATE OR REPLACE FUNCTION communities.is_pool_admin(p_pool_id integer) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
    AS $$
    SELECT EXISTS (
        SELECT 1 FROM communities.eesupool_member m
        WHERE m.eesupool_id = p_pool_id AND m.user_id = auth.uid() AND m.role = 'Admin'
    );
$$;

-- 3. Keyword list -----------------------------------------------------------
-- Text and terms are normalised the same way, so "H@te", "h a t e" and
-- "haaate" all reduce to the same form. match_anywhere additionally matches the
-- term inside longer words / with spaces removed; use it only for terms that
-- are never innocent substrings (it is what catches "f u c k" style evasion).
CREATE OR REPLACE FUNCTION communities.moderation_normalize(p text) RETURNS text
    LANGUAGE sql IMMUTABLE
    AS $$
    SELECT btrim(regexp_replace(
             regexp_replace(
               regexp_replace(
                 translate(lower(COALESCE(p, '')), '@$!013457', 'asioiieast'),
                 '[^a-z]+', ' ', 'g'),
               '(.)\1+', '\1', 'g'),
             '\s+', ' ', 'g'));
$$;

CREATE TABLE IF NOT EXISTS communities.moderation_term (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term text NOT NULL UNIQUE,
    term_norm text GENERATED ALWAYS AS (communities.moderation_normalize(term)) STORED,
    match_anywhere boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_by uuid DEFAULT auth.uid(),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Nobody reads or writes the list directly: it stays private to the server.
ALTER TABLE communities.moderation_term ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON communities.moderation_term FROM anon, authenticated;

