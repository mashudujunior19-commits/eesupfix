-- Returns the matched term, or NULL when the text is clean.
CREATE OR REPLACE FUNCTION communities.moderation_check(p_text text) RETURNS text
    LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = communities, public
    AS $$
DECLARE
    t text := communities.moderation_normalize(p_text);
    padded text;
    squashed text;
    hit text;
BEGIN
    IF t = '' THEN RETURN NULL; END IF;
    padded := ' ' || t || ' ';
    squashed := replace(t, ' ', '');

    SELECT mt.term INTO hit
    FROM communities.moderation_term mt
    WHERE mt.is_active AND mt.term_norm <> ''
      AND (padded LIKE '% ' || mt.term_norm || ' %'
           OR (mt.match_anywhere AND squashed LIKE '%' || replace(mt.term_norm, ' ', '') || '%'))
    LIMIT 1;

    RETURN hit;
END;
$$;
REVOKE ALL ON FUNCTION communities.moderation_check(text) FROM PUBLIC, anon, authenticated;

-- App-admin management of the list.
CREATE OR REPLACE FUNCTION communities.add_moderation_term(p_term text, p_match_anywhere boolean DEFAULT false)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    INSERT INTO communities.moderation_term (term, match_anywhere)
    VALUES (btrim(p_term), p_match_anywhere)
    ON CONFLICT (term) DO UPDATE SET is_active = true, match_anywhere = EXCLUDED.match_anywhere;
END; $$;

CREATE OR REPLACE FUNCTION communities.remove_moderation_term(p_term text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    UPDATE communities.moderation_term SET is_active = false WHERE term = btrim(p_term);
END; $$;

CREATE OR REPLACE FUNCTION communities.list_moderation_terms()
RETURNS TABLE (term text, match_anywhere boolean, is_active boolean)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
BEGIN
    IF NOT communities.is_app_admin() THEN RAISE EXCEPTION 'Not allowed'; END IF;
    RETURN QUERY SELECT mt.term, mt.match_anywhere, mt.is_active FROM communities.moderation_term mt ORDER BY mt.term;
END; $$;

GRANT EXECUTE ON FUNCTION communities.is_app_admin(), communities.is_pool_admin(integer),
    communities.add_moderation_term(text, boolean), communities.remove_moderation_term(text),
    communities.list_moderation_terms() TO authenticated;

-- 4. Sending ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION communities.send_chat_message(
    p_pool_id integer,
    p_author_id uuid,            -- eesupool_member.id of the sender
    p_content text,              -- encrypted content stored as before
    p_plain_text text,           -- plain text, used only for the moderation check
    p_reply_on_id integer,
    p_attachments jsonb,         -- JSON array of media objects
    p_hash_tags text[],
    p_broadcast_to text[],
    p_is_approved boolean        -- false for censored members
)
RETURNS TABLE (id integer, is_approved boolean, moderation_status text)
-- SECURITY DEFINER: it calls moderation_check, which regular users cannot execute
-- (so they cannot probe the term list). Membership is still verified below
-- against auth.uid(), so a caller can only send as themselves.
LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE
    hit text;
    approved boolean := p_is_approved;
    status text := 'none';
    reason text;
    new_id integer;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM communities.eesupool_member m
        WHERE m.id = p_author_id AND m.eesupool_id = p_pool_id AND m.user_id = auth.uid()
    ) THEN
        RAISE EXCEPTION 'You are not a member of this pool';
    END IF;

    hit := communities.moderation_check(p_plain_text);
    IF hit IS NOT NULL THEN
        approved := false;
        status := 'held';
        reason := 'Automatic: matched blocked term "' || hit || '"';
    END IF;

    INSERT INTO communities.message AS msg
        (eesupool_id, author_id, content, reply_on_id, attachments, hash_tags,
         broadcast_to, is_approved, is_deleted, moderation_status, moderation_reason)
    VALUES
        (p_pool_id, p_author_id, p_content, p_reply_on_id,
         CASE WHEN p_attachments IS NULL OR jsonb_typeof(p_attachments) <> 'array' THEN NULL
              ELSE ARRAY(SELECT jsonb_array_elements(p_attachments)) END,
         p_hash_tags,
         CASE WHEN p_broadcast_to IS NULL OR cardinality(p_broadcast_to) = 0 THEN NULL
              ELSE p_broadcast_to::communities.eesupool_level[] END,
         approved, false, status, reason)
    RETURNING msg.id INTO new_id;

    RETURN QUERY SELECT new_id, approved, status;
END; $$;

GRANT EXECUTE ON FUNCTION communities.send_chat_message(integer, uuid, text, text, integer, jsonb, text[], text[], boolean) TO authenticated;

-- Broadcast copies keep the moderation state of the original.
CREATE OR REPLACE FUNCTION communities.broadcast_eesupool_message() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    broadcast_level communities.eesupool_level;
    descendants_ids record;
BEGIN
    IF NEW.broadcast_to IS NOT NULL THEN
        FOREACH broadcast_level IN ARRAY NEW.broadcast_to LOOP
            FOR descendants_ids IN SELECT d.id FROM communities.get_eesupool_descendants_by_level(NEW.eesupool_id, broadcast_level) d LOOP
                INSERT INTO communities.message(
                    eesupool_id, author_id, content, reply_on_id, attachments, hash_tags,
                    is_approved, is_deleted, moderation_status, moderation_reason
                ) VALUES (
                    descendants_ids.id, NEW.author_id, NEW.content, NEW.reply_on_id,
                    NEW.attachments, NEW.hash_tags, NEW.is_approved, NEW.is_deleted,
                    NEW.moderation_status, NEW.moderation_reason
                );
            END LOOP;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$;

-- 5. Reviewing and flagging --------------------------------------------------
CREATE OR REPLACE FUNCTION communities.review_message(p_message_id integer, p_approve boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE pool integer;
BEGIN
    SELECT eesupool_id INTO pool FROM communities.message WHERE id = p_message_id;
    IF pool IS NULL THEN RAISE EXCEPTION 'Message not found'; END IF;
    IF NOT (communities.is_pool_admin(pool) OR communities.is_app_admin()) THEN
        RAISE EXCEPTION 'Not allowed';
    END IF;

    IF p_approve THEN
        UPDATE communities.message
           SET is_approved = true, moderation_status = 'approved',
               moderated_by = auth.uid(), moderated_at = now()
         WHERE id = p_message_id;
    ELSE
        UPDATE communities.message
           SET is_approved = false, is_deleted = true, moderation_status = 'rejected',
               moderated_by = auth.uid(), moderated_at = now()
         WHERE id = p_message_id;
    END IF;
END; $$;

-- Pull an already-delivered message back into the review queue.
CREATE OR REPLACE FUNCTION communities.flag_message(p_message_id integer, p_reason text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = communities, public AS $$
DECLARE pool integer;
BEGIN
    SELECT eesupool_id INTO pool FROM communities.message WHERE id = p_message_id;
    IF pool IS NULL THEN RAISE EXCEPTION 'Message not found'; END IF;
    IF NOT (communities.is_pool_admin(pool) OR communities.is_app_admin()) THEN
        RAISE EXCEPTION 'Not allowed';
    END IF;

    UPDATE communities.message
       SET is_approved = false, moderation_status = 'flagged',
           moderation_reason = COALESCE(NULLIF(btrim(p_reason), ''), 'Flagged by an admin'),
           moderated_by = auth.uid(), moderated_at = now()
     WHERE id = p_message_id AND is_deleted = false;
END; $$;

GRANT EXECUTE ON FUNCTION communities.review_message(integer, boolean),
    communities.flag_message(integer, text) TO authenticated;

-- 6. Reading: faster, and held messages are only visible to author/reviewers --
DROP FUNCTION IF EXISTS communities.get_eesupool_messages(integer, integer);

CREATE FUNCTION communities.get_eesupool_messages(pool_id integer, limit_to integer)
RETURNS TABLE (
    id integer, eesupool_id integer, author_id uuid, created_at timestamptz,
    content text, reply_on_id integer, attachments jsonb[], author_full_name text,
    reply_message jsonb, reactions jsonb, is_approved boolean, hash_tags text[],
    is_deleted boolean, message_seens uuid[],
    moderation_status text, moderation_reason text
)
LANGUAGE sql STABLE AS $$
    WITH reviewer AS (
        SELECT (communities.is_pool_admin(pool_id) OR communities.is_app_admin()) AS yes
    ),
    -- LIMIT is applied before any joins/subqueries so only the page we return
    -- is enriched.
    recent AS (
        SELECT m.*
        FROM communities.message m
        WHERE m.eesupool_id = pool_id
          AND (m.is_approved
               OR (SELECT yes FROM reviewer)
               OR EXISTS (SELECT 1 FROM communities.eesupool_member em
                          WHERE em.id = m.author_id AND em.user_id = auth.uid()))
        ORDER BY m.created_at DESC
        LIMIT limit_to
    )
    SELECT
        r.id, r.eesupool_id, r.author_id, r.created_at, r.content, r.reply_on_id, r.attachments,
        (SELECT CONCAT(p.first_name, ' ', p.last_name)
           FROM public.profile p
           JOIN communities.eesupool_member em ON p.user_id = em.user_id
          WHERE em.id = r.author_id) AS author_full_name,
        COALESCE((SELECT row_to_json(t)::jsonb
                    FROM (SELECT * FROM communities.get_message_by_id(r.reply_on_id)) t), 'null'::jsonb) AS reply_message,
        COALESCE((SELECT jsonb_agg(t)
                    FROM (SELECT * FROM communities.get_message_reactions(r.id)) t), 'null'::jsonb) AS reactions,
        r.is_approved, r.hash_tags, r.is_deleted,
        (SELECT array_agg(ms.member_id) FROM communities.message_seen ms WHERE ms.message_id = r.id) AS message_seens,
        r.moderation_status,
        CASE WHEN (SELECT yes FROM reviewer) THEN r.moderation_reason END AS moderation_reason
    FROM recent r
    ORDER BY r.created_at DESC;
$$;

ALTER FUNCTION communities.get_eesupool_messages(integer, integer) OWNER TO postgres;
GRANT EXECUTE ON FUNCTION communities.get_eesupool_messages(integer, integer) TO anon, authenticated, service_role;

-- Hash-tag listing: reuse the function above so held messages stay hidden.
CREATE OR REPLACE FUNCTION communities.get_eesupool_messages_by_hash_tag(pool_id integer, hash_tag text, limit_to integer)
RETURNS TABLE (
    id integer, eesupool_id integer, author_id uuid, created_at timestamptz,
    content text, reply_on_id integer, attachments jsonb[], author_full_name text,
    reply_message jsonb, reactions jsonb, is_approved boolean, hash_tags text[],
    is_deleted boolean, message_seens uuid[]
)
LANGUAGE sql STABLE AS $$
    SELECT g.id, g.eesupool_id, g.author_id, g.created_at, g.content, g.reply_on_id, g.attachments,
           g.author_full_name, g.reply_message, g.reactions, g.is_approved, g.hash_tags,
           g.is_deleted, g.message_seens
    FROM communities.get_eesupool_messages(pool_id, 100000) g
    WHERE hash_tag = ANY(g.hash_tags)
    ORDER BY g.created_at DESC
    LIMIT limit_to;
$$;
