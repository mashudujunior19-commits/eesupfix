  AND (o.cancelled_at IS NOT NULL OR o.status = 'Cancelled')
ON CONFLICT DO NOTHING;

INSERT INTO communities.pool_order_event (eesupool_order_id, order_id, stage, note, occurred_at)
SELECT o.eesupool_order_id, o.id, 'collected', CONCAT('Order #', o.id, ' handed over'), o.collected_at
FROM sales."order" o
WHERE o.eesupool_order_id IS NOT NULL AND o.collected_at IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO communities.pool_order_event (eesupool_order_id, stage, occurred_at)
SELECT eo.id, 'pool_order_closed', LEAST(now(), GREATEST(eo.closes_at, eo.created_at))
FROM communities.eesupool_order eo
WHERE eo.status = 'Closed'
ON CONFLICT DO NOTHING;

INSERT INTO communities.pool_order_event (eesupool_order_id, stage, note, occurred_at)
SELECT p.eesupool_order_id, 'processed', 'Packed and approved at the Centre.', p.ready_at
FROM communities.pool_order_progress p
JOIN communities.eesupool_order eo ON eo.id = p.eesupool_order_id
WHERE p.ready_at IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO communities.pool_order_event (eesupool_order_id, stage, occurred_at)
SELECT eo.id, 'delivered', eo.delivered_at
FROM communities.eesupool_order eo
WHERE eo.delivered_at IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO communities.pool_order_event (eesupool_order_id, order_id, stage, note, occurred_at)
SELECT o.eesupool_order_id, o.id, 'roles_assigned', communities.order_roles_note(o.id), o.placed_at
FROM sales."order" o
WHERE o.eesupool_order_id IS NOT NULL AND o.placed_at IS NOT NULL
  AND communities.order_roles_note(o.id) IS NOT NULL
ON CONFLICT DO NOTHING;

