DROP POLICY IF EXISTS pool_order_event_select ON communities.pool_order_event;
CREATE POLICY pool_order_event_select ON communities.pool_order_event
    FOR SELECT TO authenticated
    USING (
        public.is_admin()
        OR communities.is_pool_order_admin(eesupool_order_id)
        OR (order_id IS NULL AND EXISTS (
            SELECT 1 FROM communities.eesupool_order eo
            JOIN communities.eesupool_member m ON m.eesupool_id = eo.eesupool_id
            WHERE eo.id = eesupool_order_id AND m.user_id = auth.uid()))
        OR (order_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM sales."order" o
            WHERE o.id = order_id AND o.customer_id = auth.uid()))
        OR (order_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM communities.member_order_assignment moa
            JOIN communities.eesupool_member m ON m.id = moa.member_id
            WHERE moa.order_id = pool_order_event.order_id AND m.user_id = auth.uid()))
    );

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'communities' AND tablename = 'pool_order_event'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE communities.pool_order_event;
    END IF;
END;
$$;

-- 6. Admin list shows the stage --------------------------------------------------------------

CREATE OR REPLACE FUNCTION communities.admin_list_pool_orders(
    _eesupool_id integer DEFAULT NULL,
    _limit integer DEFAULT 300
) RETURNS jsonb
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
BEGIN
    IF NOT public.is_admin() THEN
        RAISE EXCEPTION 'Only an admin can list KasiPool orders.';
    END IF;

    RETURN COALESCE((
        SELECT jsonb_agg(row_to_json(t) ORDER BY t.created_at DESC)
        FROM (
            SELECT
                eo.id,
                eo.eesupool_id,
                ep.name AS eesupool_name,
                eo.status::text AS status,
                eo.created_at,
                eo.closes_at,
                eo.schedule_for,
                eo.delivered_at,
                eo.consolidated_into,
                communities.pool_order_stage_label(communities.pool_order_stage(eo.id)) AS stage,
                COUNT(o.id) FILTER (WHERE o.placed_at IS NOT NULL) AS placed_count,
                COUNT(o.id) FILTER (WHERE o.collected_at IS NOT NULL
                                     AND o.cancelled_at IS NULL) AS collected_count,
                COUNT(o.id) FILTER (WHERE o.placed_at IS NOT NULL
                                     AND (o.cancelled_at IS NOT NULL
                                          OR o.status = 'Cancelled')) AS cancelled_count,
                COALESCE(SUM(o.value) FILTER (WHERE o.placed_at IS NOT NULL
                                               AND o.cancelled_at IS NULL), 0) AS total_value
            FROM communities.eesupool_order eo
            JOIN communities.eesupool ep ON ep.id = eo.eesupool_id
            LEFT JOIN sales."order" o ON o.eesupool_order_id = eo.id
            WHERE _eesupool_id IS NULL OR eo.eesupool_id = _eesupool_id
            GROUP BY eo.id, ep.name
            ORDER BY eo.created_at DESC
            LIMIT GREATEST(COALESCE(_limit, 300), 1)
        ) t
    ), '[]'::jsonb);
END;
$$;

