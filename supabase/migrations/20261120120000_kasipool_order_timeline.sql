-- One KasiPool order timeline, the same for the customer app and the admin app.
--
-- communities.pool_order_event is the single source of truth. Rows are written
-- only by triggers and SECURITY DEFINER functions (never by a client), at the
-- moment each step happens, with who did it:
--
--   stage                         level        written when
--   order_placed                  member order sales.order.placed_at is set
--   pool_order_closed             pool order   eesupool_order.status -> Closed
--   processed                     pool order   pool_order_progress.ready_at is set (Centre approved)
--   delivered                     pool order   eesupool_order.delivered_at is set (handover to the KasiPool)
--   roles_assigned                member order Packer / Dispatcher assigned or changed (note lists them)
--   packing_checklist_completed   member order the Packer ticks the last item of that order's checklist
--   pin_issued                    member order the order's collection PIN is created (task 4)
--   collected                     member order the Dispatcher confirms the handover with the PIN
--   order_cancelled               member order the member order is cancelled
--   pool_order_completed          pool order   closed, and every member order collected or cancelled
--
-- Each (pool order, member order, stage) appears once; roles_assigned is
-- updated in place when the roles change. communities.get_pool_order_timeline()
-- returns the timeline for an app admin, a pool admin, or (pool-level steps plus
-- their own orders only) a member. The table is in supabase_realtime so screens
-- refresh live: subscribe to it as a change signal and refetch through the RPC.
-- Idempotent.

-- 1. Table -----------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS communities.pool_order_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eesupool_order_id integer NOT NULL
        REFERENCES communities.eesupool_order(id) ON DELETE CASCADE,
    order_id integer REFERENCES sales."order"(id) ON DELETE CASCADE,
    stage text NOT NULL CHECK (stage IN (
        'order_placed', 'pool_order_closed', 'processed', 'delivered',
        'roles_assigned', 'packing_checklist_completed', 'pin_issued',
        'collected', 'order_cancelled', 'pool_order_completed')),
    actor_user_id uuid,
    actor_name text,
    note text,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS pool_order_event_once
    ON communities.pool_order_event (eesupool_order_id, COALESCE(order_id, 0), stage);
CREATE INDEX IF NOT EXISTS pool_order_event_order_idx
    ON communities.pool_order_event (order_id) WHERE order_id IS NOT NULL;

ALTER TABLE communities.pool_order_event ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON communities.pool_order_event FROM anon;
REVOKE INSERT, UPDATE, DELETE ON communities.pool_order_event FROM authenticated;
GRANT SELECT ON communities.pool_order_event TO authenticated;
GRANT ALL ON communities.pool_order_event TO service_role;

-- 2. Helpers ---------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION communities.person_name(_user_id uuid) RETURNS text
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
    SELECT COALESCE(
        NULLIF(TRIM(CONCAT(p.first_name, ' ', p.last_name)), ''),
        NULLIF(TRIM(p.corp_name), ''),
        'A member')
    FROM public.profile p
    WHERE p.user_id = _user_id
$$;
REVOKE ALL ON FUNCTION communities.person_name(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION communities.person_name(uuid) TO authenticated, service_role;

-- Is the caller an admin of the pool that owns this pool order?
CREATE OR REPLACE FUNCTION communities.is_pool_order_admin(_eesupool_order_id integer) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM communities.eesupool_order eo
        JOIN communities.eesupool_member m
          ON m.eesupool_id = eo.eesupool_id
         AND m.user_id = auth.uid()
         AND m.as_business = communities.business_mode(auth.uid())
        WHERE eo.id = _eesupool_order_id AND m.role = 'Admin'
    )
$$;
REVOKE ALL ON FUNCTION communities.is_pool_order_admin(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION communities.is_pool_order_admin(integer) TO authenticated, service_role;

-- Records a step. _upsert = true updates an existing row (roles_assigned);
-- otherwise the first record wins. Never raises: a timeline problem must not
-- block an order.
CREATE OR REPLACE FUNCTION communities.log_pool_order_event(
    _eesupool_order_id integer,
    _order_id integer,
    _stage text,
    _actor uuid DEFAULT NULL,
    _note text DEFAULT NULL,
    _at timestamptz DEFAULT now(),
    _upsert boolean DEFAULT false
) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
BEGIN
    IF _eesupool_order_id IS NULL THEN
        RETURN;
    END IF;

    IF _upsert THEN
        UPDATE communities.pool_order_event
        SET actor_user_id = _actor,
            actor_name = CASE WHEN _actor IS NULL THEN NULL ELSE communities.person_name(_actor) END,
            note = _note,
            occurred_at = COALESCE(_at, now())
        WHERE eesupool_order_id = _eesupool_order_id
          AND COALESCE(order_id, 0) = COALESCE(_order_id, 0)
          AND stage = _stage;
        IF FOUND THEN
            RETURN;
        END IF;
    END IF;

    INSERT INTO communities.pool_order_event
        (eesupool_order_id, order_id, stage, actor_user_id, actor_name, note, occurred_at)
    VALUES (
        _eesupool_order_id, _order_id, _stage, _actor,
        CASE WHEN _actor IS NULL THEN NULL ELSE communities.person_name(_actor) END,
        _note, COALESCE(_at, now()))
    ON CONFLICT (eesupool_order_id, COALESCE(order_id, 0), stage) DO NOTHING;
EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'log_pool_order_event(%, %, %) failed: %',
        _eesupool_order_id, _order_id, _stage, SQLERRM;
END;
$$;
REVOKE ALL ON FUNCTION communities.log_pool_order_event(integer, integer, text, uuid, text, timestamptz, boolean) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION communities.log_pool_order_event(integer, integer, text, uuid, text, timestamptz, boolean) TO service_role;

-- "Packer: A · Dispatcher: B" for a member order's current assignments.
CREATE OR REPLACE FUNCTION communities.order_roles_note(_order_id integer) RETURNS text
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
    SELECT NULLIF(string_agg(
        CASE moa.privilage::text
            WHEN 'All' THEN 'Packer & Dispatcher'
            WHEN 'Collector' THEN 'Dispatcher'
            ELSE moa.privilage::text
        END || ': ' || communities.person_name(m.user_id),
        ' · ' ORDER BY moa.privilage::text), '')
    FROM communities.member_order_assignment moa
    JOIN communities.eesupool_member m ON m.id = moa.member_id
    WHERE moa.order_id = _order_id AND moa.privilage <> 'Owner'
$$;
REVOKE ALL ON FUNCTION communities.order_roles_note(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION communities.order_roles_note(integer) TO authenticated, service_role;

-- Logs pool_order_completed once the pool order is closed and every placed
-- member order is collected or cancelled. Returns true when it is complete.
-- (20261120150000_kasipool_pending_earnings.sql extends this to release
-- the pending earnings.)
CREATE OR REPLACE FUNCTION communities.check_pool_order_completed(_eesupool_order_id integer) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
DECLARE
    _done boolean;
    _at timestamptz;
BEGIN
    SELECT eo.status = 'Closed'
       AND EXISTS (SELECT 1 FROM sales."order" o
                   WHERE o.eesupool_order_id = eo.id AND o.placed_at IS NOT NULL)
       AND NOT EXISTS (SELECT 1 FROM sales."order" o
                       WHERE o.eesupool_order_id = eo.id
                         AND o.placed_at IS NOT NULL
                         AND o.cancelled_at IS NULL
                         AND o.status <> 'Cancelled'
                         AND o.collected_at IS NULL)
    INTO _done
    FROM communities.eesupool_order eo
    WHERE eo.id = _eesupool_order_id;

    IF NOT COALESCE(_done, false) THEN
        RETURN false;
    END IF;

    SELECT GREATEST(MAX(o.collected_at), MAX(o.cancelled_at)) INTO _at
    FROM sales."order" o WHERE o.eesupool_order_id = _eesupool_order_id;

    PERFORM communities.log_pool_order_event(
        _eesupool_order_id, NULL, 'pool_order_completed', NULL,
        'Every order was collected or cancelled.', COALESCE(_at, now()));
    RETURN true;
END;
$$;
REVOKE ALL ON FUNCTION communities.check_pool_order_completed(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION communities.check_pool_order_completed(integer) TO service_role;

-- 3. Triggers that write the steps -------------------------------------------------------------

-- Member orders: placed, cancelled, collected.
CREATE OR REPLACE FUNCTION communities.timeline_on_member_order() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
DECLARE
    _was_collected boolean := TG_OP = 'UPDATE' AND OLD.collected_at IS NOT NULL;
    _was_cancelled boolean := TG_OP = 'UPDATE'
        AND (OLD.cancelled_at IS NOT NULL OR OLD.status = 'Cancelled');
    _was_placed boolean := TG_OP = 'UPDATE' AND OLD.placed_at IS NOT NULL;
BEGIN
    IF NEW.eesupool_order_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.placed_at IS NOT NULL AND NOT _was_placed THEN
        PERFORM communities.log_pool_order_event(
            NEW.eesupool_order_id, NEW.id, 'order_placed', NEW.customer_id,
            CONCAT('Order #', NEW.id), NEW.placed_at);
    END IF;

    IF (NEW.cancelled_at IS NOT NULL OR NEW.status = 'Cancelled') AND NOT _was_cancelled
       AND NEW.placed_at IS NOT NULL THEN
        PERFORM communities.log_pool_order_event(
            NEW.eesupool_order_id, NEW.id, 'order_cancelled', auth.uid(),
            CONCAT('Order #', NEW.id), COALESCE(NEW.cancelled_at, now()));
        PERFORM communities.check_pool_order_completed(NEW.eesupool_order_id);
    END IF;

    IF NEW.collected_at IS NOT NULL AND NOT _was_collected THEN
        PERFORM communities.log_pool_order_event(
            NEW.eesupool_order_id, NEW.id, 'collected', auth.uid(),
            CONCAT('Order #', NEW.id, ' handed over'), NEW.collected_at);
        PERFORM communities.check_pool_order_completed(NEW.eesupool_order_id);
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS timeline_on_member_order_trigger ON sales."order";
CREATE TRIGGER timeline_on_member_order_trigger
    AFTER INSERT OR UPDATE OF placed_at, cancelled_at, collected_at, status ON sales."order"
    FOR EACH ROW EXECUTE FUNCTION communities.timeline_on_member_order();

-- Pool orders: closed, delivered.
CREATE OR REPLACE FUNCTION communities.timeline_on_pool_order() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
BEGIN
    IF NEW.status = 'Closed' AND OLD.status IS DISTINCT FROM 'Closed' THEN
        PERFORM communities.log_pool_order_event(
            NEW.id, NULL, 'pool_order_closed', auth.uid(),
            CASE WHEN auth.uid() IS NULL THEN 'Closed automatically at the deadline.' END,
            LEAST(now(), GREATEST(COALESCE(NEW.closes_at, now()), NEW.created_at)));
        PERFORM communities.check_pool_order_completed(NEW.id);
    END IF;

    IF NEW.delivered_at IS NOT NULL AND OLD.delivered_at IS NULL THEN
        PERFORM communities.log_pool_order_event(
            NEW.id, NULL, 'delivered', auth.uid(), NULL, NEW.delivered_at);
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS timeline_on_pool_order_trigger ON communities.eesupool_order;
CREATE TRIGGER timeline_on_pool_order_trigger
    AFTER UPDATE OF status, delivered_at ON communities.eesupool_order
    FOR EACH ROW EXECUTE FUNCTION communities.timeline_on_pool_order();

-- Centre progress: processed = approved at the Centre (ready to load).
CREATE OR REPLACE FUNCTION communities.timeline_on_pool_progress() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
BEGIN
    IF NEW.ready_at IS NOT NULL
       AND (TG_OP = 'INSERT' OR OLD.ready_at IS NULL) THEN
        PERFORM communities.log_pool_order_event(
            NEW.eesupool_order_id, NULL, 'processed', NULL,
            'Packed and approved at the Centre.', NEW.ready_at);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS timeline_on_pool_progress_trigger ON communities.pool_order_progress;
CREATE TRIGGER timeline_on_pool_progress_trigger
    AFTER INSERT OR UPDATE OF ready_at ON communities.pool_order_progress
    FOR EACH ROW EXECUTE FUNCTION communities.timeline_on_pool_progress();

-- Roles: logged (or updated) whenever a member order's assignments change.
CREATE OR REPLACE FUNCTION communities.timeline_on_assignment() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
AS $$
DECLARE
    _order_id integer := COALESCE(NEW.order_id, OLD.order_id);
    _pool_order_id integer := COALESCE(NEW.eesupool_ord_id, OLD.eesupool_ord_id);
    _note text;
BEGIN
    _note := communities.order_roles_note(_order_id);
    IF _note IS NOT NULL THEN
        PERFORM communities.log_pool_order_event(
            _pool_order_id, _order_id, 'roles_assigned', auth.uid(), _note, now(), true);
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS timeline_on_assignment_trigger ON communities.member_order_assignment;
CREATE TRIGGER timeline_on_assignment_trigger
    AFTER INSERT OR UPDATE OR DELETE ON communities.member_order_assignment
    FOR EACH ROW EXECUTE FUNCTION communities.timeline_on_assignment();

-- 4. Reading the timeline ------------------------------------------------------------------------

-- Returns {pool_order, stage, stage_label, events[], orders[]} or raises when the
-- caller may not see it. Admins (app or pool) see every member order with names;
-- a member sees the pool-level steps and only the orders they placed or hold a
-- role on.
CREATE OR REPLACE FUNCTION communities.get_pool_order_timeline(_eesupool_order_id integer) RETURNS jsonb
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
DECLARE
    _is_admin boolean := public.is_admin() OR communities.is_pool_order_admin(_eesupool_order_id);
    _visible integer[];
    _pool jsonb;
    _stage text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM communities.eesupool_order WHERE id = _eesupool_order_id) THEN
        RAISE EXCEPTION 'KasiPool order % was not found.', _eesupool_order_id;
    END IF;

    IF _is_admin THEN
        SELECT array_agg(o.id) INTO _visible
        FROM sales."order" o WHERE o.eesupool_order_id = _eesupool_order_id;
    ELSE
        SELECT array_agg(DISTINCT o.id) INTO _visible
        FROM sales."order" o
        LEFT JOIN communities.member_order_assignment moa ON moa.order_id = o.id
        LEFT JOIN communities.eesupool_member m ON m.id = moa.member_id
        WHERE o.eesupool_order_id = _eesupool_order_id
          AND (o.customer_id = auth.uid() OR (m.user_id = auth.uid() AND moa.privilage <> 'Owner'));

        IF _visible IS NULL AND NOT EXISTS (
            SELECT 1 FROM communities.eesupool_order eo
            JOIN communities.eesupool_member m ON m.eesupool_id = eo.eesupool_id
            WHERE eo.id = _eesupool_order_id AND m.user_id = auth.uid()
        ) THEN
            RAISE EXCEPTION 'You cannot view this KasiPool order.';
        END IF;
    END IF;
    _visible := COALESCE(_visible, '{}');

    SELECT jsonb_build_object(
        'id', eo.id, 'eesupool_id', eo.eesupool_id, 'eesupool_name', ep.name,
        'status', eo.status::text, 'created_at', eo.created_at, 'closes_at', eo.closes_at,
        'schedule_for', eo.schedule_for, 'delivered_at', eo.delivered_at)
    INTO _pool
    FROM communities.eesupool_order eo
    JOIN communities.eesupool ep ON ep.id = eo.eesupool_id
    WHERE eo.id = _eesupool_order_id;

    _stage := communities.pool_order_stage(_eesupool_order_id);

    RETURN jsonb_build_object(
        'pool_order', _pool,
        'is_admin', _is_admin,
        'stage', _stage,
        'stage_label', communities.pool_order_stage_label(_stage),
        'events', COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                'id', e.id, 'stage', e.stage,
                'label', communities.pool_order_stage_label(e.stage),
                'order_id', e.order_id,
                'actor_name', e.actor_name,
                'note', e.note,
                'occurred_at', e.occurred_at,
                'mine', e.order_id IS NOT NULL
                        AND EXISTS (SELECT 1 FROM sales."order" o
                                    WHERE o.id = e.order_id AND o.customer_id = auth.uid()))
                ORDER BY e.occurred_at, e.id)
            FROM communities.pool_order_event e
            WHERE e.eesupool_order_id = _eesupool_order_id
              AND (e.order_id IS NULL OR e.order_id = ANY(_visible))
        ), '[]'::jsonb),
        'orders', COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                'order_id', o.id,
                'customer_name', communities.person_name(o.customer_id),
                'status', CASE
                    WHEN o.cancelled_at IS NOT NULL OR o.status = 'Cancelled' THEN 'Cancelled'
                    WHEN o.collected_at IS NOT NULL THEN 'Collected'
                    ELSE o.status::text END,
                'placed_at', o.placed_at,
                'collected_at', o.collected_at,
                'roles', communities.order_roles_note(o.id),
                'checklist_completed_at', (SELECT occurred_at FROM communities.pool_order_event
                    WHERE order_id = o.id AND stage = 'packing_checklist_completed'),
                'pin_issued_at', (SELECT occurred_at FROM communities.pool_order_event
                    WHERE order_id = o.id AND stage = 'pin_issued'),
                'collected_by', (SELECT actor_name FROM communities.pool_order_event
                    WHERE order_id = o.id AND stage = 'collected'),
                'mine', o.customer_id = auth.uid())
                ORDER BY o.id)
            FROM sales."order" o
            WHERE o.id = ANY(_visible) AND o.placed_at IS NOT NULL
        ), '[]'::jsonb)
    );
END;
$$;

-- Furthest stage the pool order has reached. Member-order steps only count
-- once the bulk order is delivered (roles can be set earlier); while some
-- members have collected and others have not, the stage is 'collecting'.
CREATE OR REPLACE FUNCTION communities.pool_order_stage(_eesupool_order_id integer) RETURNS text
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public'
AS $$
    WITH best AS (
        SELECT e.stage
        FROM communities.pool_order_event e
        WHERE e.eesupool_order_id = _eesupool_order_id
          AND e.stage <> 'order_cancelled'
          AND (e.order_id IS NULL OR e.stage = 'order_placed' OR EXISTS (
                SELECT 1 FROM communities.pool_order_event d
                WHERE d.eesupool_order_id = _eesupool_order_id AND d.stage = 'delivered'))
        ORDER BY array_position(ARRAY[
            'order_placed', 'pool_order_closed', 'processed', 'delivered',
            'roles_assigned', 'packing_checklist_completed', 'pin_issued',
            'collected', 'pool_order_completed'], e.stage) DESC
        LIMIT 1
    )
    SELECT CASE
        WHEN (SELECT stage FROM best) = 'collected' THEN 'collecting'
        ELSE COALESCE((SELECT stage FROM best), 'open') END
$$;

CREATE OR REPLACE FUNCTION communities.pool_order_stage_label(_stage text) RETURNS text
    LANGUAGE sql IMMUTABLE
    SET search_path TO 'public'
AS $$
    SELECT CASE _stage
        WHEN 'open' THEN 'Open for orders'
        WHEN 'order_placed' THEN 'Order placed'
        WHEN 'pool_order_closed' THEN 'KasiPool order closed'
        WHEN 'processed' THEN 'Processed at the Centre'
        WHEN 'delivered' THEN 'Delivered to the KasiPool'
        WHEN 'roles_assigned' THEN 'Roles assigned'
        WHEN 'packing_checklist_completed' THEN 'Packing checklist completed'
        WHEN 'pin_issued' THEN 'Collection PIN issued'
        WHEN 'collected' THEN 'Collected'
        WHEN 'collecting' THEN 'Members collecting'
        WHEN 'order_cancelled' THEN 'Order cancelled'
        WHEN 'pool_order_completed' THEN 'KasiPool order completed'
        ELSE _stage END
$$;

REVOKE ALL ON FUNCTION communities.get_pool_order_timeline(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION communities.get_pool_order_timeline(integer) TO authenticated, service_role;
REVOKE ALL ON FUNCTION communities.pool_order_stage(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION communities.pool_order_stage(integer) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION communities.pool_order_stage_label(text) TO authenticated, service_role;

